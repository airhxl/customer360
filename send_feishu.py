"""
客户360°助手 · 飞书群推送：把消息发到飞书群（最小验证）
================================================================================
【本脚本在干什么】
  往你刚建的飞书群里发一条测试消息——验证Webhook通不通。

【原理】
  飞书群自定义机器人 = 群里的"收件箱"。
  程序往它的Webhook地址 POST 一段JSON，消息就出现在群里。
  就这么简单：一个URL + 一条POST请求。

  JSON格式：
    {
      "msg_type": "text",
      "content": {"text": "消息内容"}
    }

【注意】
  你建机器人时设了"自定义关键词=客户360"，所以消息文本里必须包含
  "客户360"这几个字，否则飞书会拒绝发送（这是安全设置，防止乱发）。
================================================================================
"""

import requests
from secret_local import FEISHU_WEBHOOK   # Webhook地址在本地配置（不写进代码）

# =====================================================================
# 发送一条消息（注意文本里带了"客户360"，满足关键词校验）
# =====================================================================
msg = "【客户360】测试消息：客户风险提醒机器人已上线，每周一自动推送合同到期与AI风险摘要。"
resp = requests.post(
    FEISHU_WEBHOOK,
    json={
        "msg_type": "text",
        "content": {"text": msg},
    },
)
result = resp.json()

# =====================================================================
# 判断结果：code=0 表示发送成功（飞书所有接口都用code判断，和前面API一样）
# =====================================================================
if result.get("code") == 0:
    print("✅ 消息发送成功！去飞书群看一眼，应该能看到：")
    print("   ", msg)
else:
    print(f"❌ 发送失败：code={result.get('code')} msg={result.get('msg')}")
